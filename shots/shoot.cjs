const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' })
  process.on('unhandledRejection', (e) => console.log('ERR', e.message))
  const p = await b.newPage({ viewport: { width: 1280, height: 1000 } })
  p.on('console', (m) => m.type() === 'error' && console.log('console:', m.text()))
  p.setDefaultTimeout(12000)
  const base = 'http://localhost:4173/'
  async function teamFrom(hash, name) {
   try {
    await p.goto(base + hash)
    await p.waitForSelector('.logo-link', { timeout: 20000 })
    await p.locator('.logo-link').first().click()
    await p.waitForSelector('.tc-sched, .tc-panel .muted', { timeout: 20000 })
    await p.waitForTimeout(2500)
    await p.screenshot({ path: `shots/${name}.png` })
    const rows = await p.locator('.tc-schedule li').count()
    console.log(name, 'rows', rows, 'text:', (await p.locator('.tc-panel').innerText()).slice(0, 600).replace(/\n/g, ' | '))
   } catch (e) {
    console.log(name, 'FAILED', e.message.split('\n')[0])
    await p.screenshot({ path: `shots/${name}-fail.png` })
    console.log((await p.locator('main').innerText()).slice(0, 400).replace(/\n/g, ' | '))
   }
  }
  await teamFrom('#/cfb/scores', 'cfb-scores')
  await teamFrom('#/cfb/rankings', 'cfb')
  await p.locator('.tc-sched .seg button').nth(1).click().catch(() => {})
  await p.waitForTimeout(3000)
  await p.screenshot({ path: 'shots/cfb-2025.png' })
  console.log('cfb 2025 rows', await p.locator('.tc-schedule li').count(), (await p.locator('.tc-sched').innerText()).slice(-500).replace(/\n/g, ' | '))
  await teamFrom('#/mbb/standings', 'mbb')
  await p.locator('text=See last season').click().catch((e) => console.log('no last-season button', e.message))
  await p.waitForTimeout(3000)
  await p.screenshot({ path: 'shots/mbb-last.png' })
  console.log('mbb last rows', await p.locator('.tc-schedule li').count(), (await p.locator('.tc-sched').innerText()).slice(-400).replace(/\n/g, ' | '))
  await p.locator('.tc-game').first().click().catch(() => {})
  await p.waitForTimeout(3000)
  await p.screenshot({ path: 'shots/mbb-game.png' })
  await teamFrom('#/bsb/standings', 'bsb')
  await teamFrom('#/sb/standings', 'sb')
  await teamFrom('#/wbb/rankings', 'wbb')
  await p.setViewportSize({ width: 390, height: 844 })
  await teamFrom('#/cfb/rankings', 'cfb-mobile')
  await b.close()
})()
